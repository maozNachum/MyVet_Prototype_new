-- Reliable live refresh and server-authorized payment settlement.
-- Portal payments in this graduation-project build are a clearly labelled
-- simulation. A production gateway must replace the owner RPC with a verified
-- provider webhook before real card details or money are accepted.

do $$
declare
  table_name text;
  live_tables text[] := array[
    'appointments', 'patients', 'owners', 'payments', 'conversations',
    'messages', 'lab_orders', 'hospitalizations', 'inventory', 'vaccinations'
  ];
begin
  foreach table_name in array live_tables loop
    if to_regclass(format('public.%I', table_name)) is not null
      and not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = table_name
      ) then
      execute format('alter publication supabase_realtime add table public.%I', table_name);
    end if;
  end loop;
end $$;

-- Remove broad prototype policies that could let one authenticated user see or
-- mutate another user's medical/billing rows. The explicit staff and owner
-- policies from 202607150002_myvet_rls_hardening.sql remain in force.
do $$
declare
  policy_row record;
  protected_tables text[] := array[
    'staff', 'owners', 'patients', 'appointments', 'payments', 'payment_items',
    'medical_visits', 'physical_exams', 'medical_problems', 'differential_diagnoses',
    'prescriptions', 'lab_orders', 'documents', 'hospitalizations', 'conversations',
    'messages', 'message_attachments', 'video_sessions', 'notifications', 'reminders',
    'vaccinations', 'inventory', 'service_catalog'
  ];
begin
  for policy_row in
    select tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = any(protected_tables)
      and (policyname ilike 'myvet_demo_%' or policyname ilike 'allow anon%')
  loop
    execute format('drop policy if exists %I on public.%I', policy_row.policyname, policy_row.tablename);
  end loop;
end $$;

